pub const OUTPUT: &str = "utils.js";
fn render() -> Result<String> {
    let mut emergency = BTreeMap::new();
    for (&name,&path) in contract::API_EVENTS.iter().zip(contract::API_PATHS).take(contract::EMERGENCY_COUNT) {
        emergency.insert(std::str::from_utf8(name)?, std::str::from_utf8(path)?.split('.').collect::<Vec<_>>());
    }
    let table = serde_json::to_string(&emergency)?;
    Ok(String::from("// @generated by the Rust browser API binding generator. DO NOT EDIT.\n") + &HOST.replace("__CPO_EMERGENCY__", &table))
}
pub fn generate(stage:&Path) -> Result<()> {
    fs::write(stage.join(OUTPUT), render()?)?;
    println!("Generated {OUTPUT} from Rust browser transport policy");
    Ok(())
}
